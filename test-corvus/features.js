// Tes fitur corvus-tg (butuh `npm run build` dulu)
const assert = require('assert'), fs = require('fs'), os = require('os'), path = require('path')
const c = require('../lib/corvus')
;(async () => {
  // ---- rich message native ----
  const r = c.rich().title('Laporan','📊').text(['Halo ', c.rt.bold('dunia')])
    .table(['Nama','Skor'],[['Ani',90],['Budi',75]],{striped:true})
    .fold('Detail',['a','b'])
    .fold('Bersarang',(x)=>x.text('dalam').list(['satu','dua'],true))
    .checklist([{text:'Deploy',done:true},'Docs'],'Todo')
    .code('<x>','js').divider()
    .buttons([c.Btn.cb('OK','ok','green'),c.Btn.cb('Ungu','p','purple')],'center')
  const inp = r.toInput(), types = inp.blocks.map(b=>b.type)
  assert.deepStrictEqual(types,['heading','paragraph','table','details','details','paragraph','list','pre','divider','buttons'])
  const tbl = inp.blocks[2]; assert(tbl.is_striped && tbl.cells[0][0].is_header && tbl.cells[1][1].align==='left' && tbl.cells[1][1].valign==='middle')
  const ck = inp.blocks[6]; assert(ck.items[0].has_checkbox && ck.items[0].is_checked===true && !('is_checked' in ck.items[1]))
  assert.strictEqual(inp.blocks[3].blocks.length,2)
  assert.strictEqual(inp.blocks[9].buttons[0].style,'success')
  assert.deepStrictEqual(r.validate(),[])
  assert.throws(()=>c.rich().text('x').markdown('y'),/sudah ada blok/); assert.throws(()=>c.rich().markdown('y').text('x'),/mode markdown/)
  assert.deepStrictEqual(Object.keys(c.rich().markdown('# hi').toInput()),['markdown'])
  const html = r.toLegacyHTML(); assert(html.includes('<blockquote expandable>')&&html.includes('┌')===false&&html.includes('☑')&&html.includes('&lt;x&gt;'))
  const big = c.rich(); for (let i=0;i<1200;i++) big.text('x')
  const chunks = big.toChunks(); assert(chunks.length>=3 && chunks.every(x=>x.blocks.length<=450))
  assert(c.rich().table(null,[[1,2]]).toInput().blocks[0].cells.length===1)
  assert.throws(()=>c.rich().table(Array(21).fill('h'),[]),/20 kolom/)
  // ---- pengiriman: sendRichMessage, pecah, edit, fallback ----
  const calls=[]; const tg={callApi:async(m,p)=>{calls.push([m,p]);return {message_id:1}}}
  await c.sendRich(tg,5,big,{reply_markup:{inline_keyboard:[]},disable_notification:true})
  assert(calls.length===chunks.length && calls.every(x=>x[0]==='sendRichMessage'&&x[1].chat_id===5&&x[1].disable_notification))
  assert(calls.at(-1)[1].reply_markup && !calls[0][1].reply_markup)
  calls.length=0; await c.editRich(tg,5,9,r); assert(calls[0][0]==='editMessageText'&&calls[0][1].message_id===9&&calls[0][1].rich_message.blocks)
  calls.length=0; await c.sendRichDraft(tg,5,77,c.rich().thinking('...'),{can_stop:true}); assert(calls[0][0]==='sendRichMessageDraft'&&calls[0][1].draft_id===77)
  assert.throws(()=>c.sendRichDraft(tg,5,0,'x'),/nol/)
  const sent=[]; const tg404={callApi:async()=>{const e=new Error('404: Not Found');e.code=404;throw e},sendMessage:async(id,t,x)=>{sent.push([id,t,x]);return {}}}
  await c.sendRich(tg404,5,r); assert(sent[0][2].parse_mode==='HTML'&&sent[0][1].includes('<b>')&&sent[0][2].reply_markup.inline_keyboard[0].length===2)
  await assert.rejects(c.sendRich(tg404,5,r,{fallback:false}))
  const md = new c.CorvusAI({apiKey:'x'}).toRich('**hi**'); assert(md.toInput().markdown.startsWith('## ✦ AI'))
  assert(c.Btn.cb('U','u','purple').text.startsWith('🟪'))
  assert(c.Btn.cb('O','o','green').style==='success' && c.Btn.cb('R','r','#ff0000').style==='danger')
  assert(c.Btn.cb('Y','y','#ffd000').text.startsWith('🟨') && c.Btn.cb('R','r',{color:'#ff0000',mode:'emoji'}).text.startsWith('🟥'))
  const kb = c.colorKeyboard([c.Btn.cb('A','a','blue'),c.Btn.cb('B','b','purple'),c.Btn.cb('C','c','yellow')],{columns:2})
  assert(kb.reply_markup.inline_keyboard.length===2)
  const ai = new c.CorvusAI({apiKey:'x', prompt:'jawab pendek'})
  assert(c.markdownToHTML('**hi** `a<b`\n```js\nx<1\n```').includes('<pre><code class="language-js">x&lt;1'))
  assert(ai.buildSystem().includes('corvus-ai') && ai.buildSystem().includes('PROMPT TAMBAHAN'))
  const cs = ai.buildSystem({mode:'custom',system:'Jadi bajak laut'}); assert(cs.includes('WAJIB DIPATUHI') && cs.includes('bajak laut') && cs.includes('corvus-tg'))
  assert(ai.explainLocal(new Error('409: Conflict')))
  let e; try { await new c.CorvusAI({}).ask('hi') } catch(x){ e=x } assert(e.code==='NO_API_KEY')
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'corvus-plugins-'))
  const bot = new c.Corvus('123:abc')
  fs.writeFileSync(dir+'/a.js', "module.exports=(c)=>{c.on('text',ctx=>{ctx.reply('v1')})}")
  bot.hotReload({dir,interval:100,silent:true}); await bot.loaderReady
  const out=[]; const upd={update_id:1,message:{message_id:1,date:1,chat:{id:1,type:'private'},from:{id:1,is_bot:false,first_name:'a'},text:'hi'}}
  const fire=()=>{const ctx=new c.CorvusContext(upd,{},{id:1,username:'b'});ctx.reply=(t)=>out.push(t);return bot.loader.middleware()(ctx,async()=>{})}
  await fire()
  fs.writeFileSync(dir+'/a.js', "module.exports=(c)=>{c.on('text',ctx=>{ctx.reply('v2')})}"); await new Promise(r=>setTimeout(r,400)); await fire()
  fs.writeFileSync(dir+'/a.js', "module.exports=123"); await new Promise(r=>setTimeout(r,400)); await fire()
  assert.deepStrictEqual(out,['v1','v2','v2']); await bot.loader.stop()
  assert.throws(()=>new c.CorvusUserbot({}), /apiId/)
  const ub = new c.CorvusUserbot({apiId:1, apiHash:'x'}); assert(ub.calls && ub.client)   // tanpa paket tambahan
  console.log('features OK'); process.exit(0)
})().catch(e=>{console.error('FAIL',e);process.exit(1)})
